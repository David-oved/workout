import type { Portion } from '../core/types';

/**
 * שכבת "מצרכי יסוד": מזונות נפוצים עם שם קצר ובהיר, מנות טיפוסיות ומקדם התנפחות/התכווצות בבישול.
 * הערכים התזונתיים עצמם מגיעים ממאגר משרד הבריאות (קוד המזון), חוץ מכמה מזונות ש"אין" בו וסומנו x:.
 * kind: raw = משקל לפני בישול, cooked = אחרי בישול. y = משקל מבושל / משקל גולמי.
 */
export interface Staple {
  code?: number;
  x?: [string, number, number, number, number]; // slug (שם מזהה), קל׳, חלבון, פחמימה, שומן ל-100 ג׳ (ערכים כלליים לא מהמאגר)
  name: string;
  kind?: 'raw' | 'cooked';
  y?: number;
  portions?: Portion[];
  alias?: string;
}

const P = (s: string): Portion[] => s.split('|').map((x) => { const [l, g] = x.split(':'); return { l, g: Number(g) }; });
const S = (code: number, name: string, portions = '', kind?: 'raw' | 'cooked', y?: number, alias?: string): Staple => ({ code, name, portions: portions ? P(portions) : undefined, kind, y, alias });
const X = (slug: string, name: string, k: number, p: number, c: number, f: number, portions = '', kind?: 'raw' | 'cooked', y?: number, alias?: string): Staple => ({
  x: [slug, k, p, c, f], name, portions: portions ? P(portions) : undefined, kind, y, alias,
});

